#!/usr/bin/env bash
# KhetSe one-shot VM bootstrap (Ubuntu 22.04 / 24.04, Debian 12).
# Run as root:  bash deploy/vm/bootstrap.sh api.yourdomain.com
#
# What it does: installs Docker if missing, opens 80/443, generates a .env with
# fresh secrets, builds and starts the production stack (Postgres + Redis +
# FastAPI + Caddy with automatic HTTPS), applies migrations and seeds demo data.
set -euo pipefail

DOMAIN="${1:?usage: bash deploy/vm/bootstrap.sh api.yourdomain.com}"
APP_DIR="/opt/khetse"
REPO_URL="${REPO_URL:-https://github.com/Venkatasai200628/khetse.git}"

[ "$(id -u)" -eq 0 ] || { echo "run as root (sudo bash $0 $DOMAIN)"; exit 1; }

echo "==> Firewall: allow ssh/http/https"
if command -v ufw >/dev/null; then
  ufw allow OpenSSH >/dev/null 2>&1 || true
  ufw allow 80/tcp  >/dev/null 2>&1 || true
  ufw allow 443/tcp >/dev/null 2>&1 || true
  ufw --force enable >/dev/null 2>&1 || true
fi

echo "==> Docker"
if ! command -v docker >/dev/null; then
  curl -fsSL https://get.docker.com | sh
  systemctl enable --now docker
fi
docker compose version >/dev/null

echo "==> Source"
if [ ! -d "$APP_DIR" ]; then
  git clone "$REPO_URL" "$APP_DIR"
else
  git -C "$APP_DIR" pull --ff-only || true
fi
cd "$APP_DIR"

echo "==> .env with fresh secrets"
if [ ! -f .env ]; then
  cat > .env <<ENV
# Generated by deploy/vm/bootstrap.sh — keep this file private.
KHEETSE_DOMAIN=$DOMAIN
POSTGRES_PASSWORD=$(openssl rand -hex 24)
JWT_SECRET=$(openssl rand -hex 48)
KHEETSE_ENV=demo
DEMO_MODE=true
CORS_ORIGINS=*
LOG_LEVEL=INFO
ENV
  chmod 600 .env
fi

echo "==> Build and start"
docker compose -f docker-compose.prod.yml up -d --build

echo "==> Wait for the database, then migrate + seed"
sleep 10
docker compose -f docker-compose.prod.yml exec -T backend python -m alembic upgrade head
docker compose -f docker-compose.prod.yml exec -T backend python -m app.db.seed

echo
echo "KhetSe API:  https://$DOMAIN  (certificate auto-issued by Caddy — first start may take ~1 min)"
echo "Health:      curl https://$DOMAIN/health"
echo "Docs:        https://$DOMAIN/docs"
echo
echo "Frontend rebuild (from your dev machine):"
echo "  cd app && flutter build web --release --dart-define=API_BASE_URL=https://$DOMAIN/api/v1"
